"""Permutation-composition (state tracking) data generation.

Motivation: integer addition turned out to be PARALLELIZABLE (carry-lookahead,
constant depth), so it is a weak test of "depth ~ length of the sequential
dependency chain". This module provides a task with an IRREDUCIBLE sequential
dependency, plus a parallelizable control with an identical surface form.

Two task conditions (same vocabulary, same sequence length, same answer format):
  - S5: compose K permutations drawn from the full symmetric group S5.
        S5 is NON-SOLVABLE -> its word problem is NC^1-complete (Barrington),
        i.e. it CANNOT be collapsed to constant depth. Analogue of SEQ.
  - C5: compose K permutations drawn from the cyclic subgroup <(0 1 2 3 4)>.
        Cyclic => abelian => composition reduces to addition of exponents
        mod 5, computable in parallel by a prefix scan. Analogue of INDEP.

Token sequence:
    [BOS] p1 p2 ... pK [EQ] d0 d1 d2 d3 d4 [EOS]
where p_i are permutation tokens and d_j is the image of j under the composed
permutation. Length = K + 8 for both tasks and every example at a given K.

L(x) (the sequential dependency length) = number of NON-IDENTITY permutations
in the sequence; identity elements are no-ops. Balanced sampling over L(x) is
constructed directly, exactly as for the carry-chain task.
"""

from __future__ import annotations

from itertools import permutations as _iter_perms
from typing import Dict, List, Optional, Sequence, Set, Tuple

import numpy as np

# --------------------------------------------------------------------------
# Group: S5 and its cyclic subgroup C5
# --------------------------------------------------------------------------
NELEM = 5  # permutations act on {0,1,2,3,4}

ALL_PERMS: List[Tuple[int, ...]] = sorted(_iter_perms(range(NELEM)))  # 120
PERM_TO_ID: Dict[Tuple[int, ...], int] = {p: i for i, p in enumerate(ALL_PERMS)}
IDENTITY: Tuple[int, ...] = tuple(range(NELEM))

# cyclic subgroup generated by the 5-cycle (0 1 2 3 4): c[i] = (i+1) % 5
_CYCLE: Tuple[int, ...] = tuple((i + 1) % NELEM for i in range(NELEM))


def _compose(state: Sequence[int], p: Sequence[int]) -> Tuple[int, ...]:
    """Apply `state` first, then `p`:  result[i] = p[state[i]]."""
    return tuple(p[state[i]] for i in range(NELEM))


def _cyclic_group() -> List[Tuple[int, ...]]:
    out, cur = [], IDENTITY
    for _ in range(NELEM):
        out.append(cur)
        cur = _compose(cur, _CYCLE)
    return out


C5_PERMS: List[Tuple[int, ...]] = _cyclic_group()  # 5 elements incl. identity

TASKS = ("S5", "C5")


def group_elements(task: str) -> List[Tuple[int, ...]]:
    if task == "S5":
        return ALL_PERMS
    if task == "C5":
        return C5_PERMS
    raise ValueError(f"unknown task {task!r}")


# --------------------------------------------------------------------------
# Vocabulary
# --------------------------------------------------------------------------
PAD_ID = 0
BOS_ID = 1
EOS_ID = 2
EQ_ID = 3
PERM_OFFSET = 4                      # permutation tokens: 4 .. 123
DIGIT_OFFSET = PERM_OFFSET + len(ALL_PERMS)   # answer digits 0..4 -> 124..128
VOCAB_SIZE = DIGIT_OFFSET + NELEM    # 129

IGNORE_INDEX = -100


def seq_len_for(K: int) -> int:
    """Total token-sequence length for K composed permutations."""
    return K + 8  # BOS + K + EQ + 5 answer digits + EOS


def perm_token(p: Sequence[int]) -> int:
    return PERM_OFFSET + PERM_TO_ID[tuple(p)]


def token_perm(tok: int) -> Tuple[int, ...]:
    return ALL_PERMS[int(tok) - PERM_OFFSET]


# --------------------------------------------------------------------------
# Sequential dependency length
# --------------------------------------------------------------------------
def chain_length(perms: Sequence[Sequence[int]]) -> int:
    """Number of NON-IDENTITY permutations = number of real sequential steps."""
    return sum(1 for p in perms if tuple(p) != IDENTITY)


def compose_all(perms: Sequence[Sequence[int]]) -> Tuple[int, ...]:
    """Left-to-right composition of the whole sequence."""
    state = IDENTITY
    for p in perms:
        state = _compose(state, p)
    return state


# --------------------------------------------------------------------------
# Example construction
# --------------------------------------------------------------------------
def build_example(perms: Sequence[Sequence[int]]) -> Tuple[np.ndarray, np.ndarray]:
    """(input_ids, target_ids); loss only on the answer digits + EOS."""
    result = compose_all(perms)
    tokens: List[int] = [BOS_ID]
    tokens += [perm_token(p) for p in perms]
    tokens.append(EQ_ID)
    answer_start = len(tokens)
    tokens += [DIGIT_OFFSET + int(v) for v in result]
    tokens.append(EOS_ID)

    input_ids = np.array(tokens, dtype=np.int64)
    target_ids = np.full_like(input_ids, IGNORE_INDEX)
    for pos in range(answer_start - 1, len(tokens) - 1):
        target_ids[pos] = input_ids[pos + 1]
    return input_ids, target_ids


def _make_with_chain(task: str, K: int, L: int, rng: np.random.Generator):
    """Sequence of K perms with EXACTLY L non-identity elements at random spots."""
    non_id = [p for p in group_elements(task) if p != IDENTITY]
    perms: List[Tuple[int, ...]] = [IDENTITY] * K
    if L > 0:
        pos = rng.choice(K, size=L, replace=False)
        for i in pos:
            perms[int(i)] = non_id[int(rng.integers(len(non_id)))]
    return perms


def make_example(task: str, K: int, rng: np.random.Generator):
    """One example with chain length drawn uniformly from {0..K}.

    Sampling L uniformly (rather than every position uniformly from the group)
    ensures the training distribution COVERS all dependency lengths — otherwise
    L(x) would concentrate at K and the accuracy-vs-L(x) plot would be
    out-of-distribution at small L.
    """
    L = int(rng.integers(0, K + 1))
    return build_example(_make_with_chain(task, K, L, rng))


def example_key(input_ids: Sequence[int]) -> str:
    return ",".join(str(int(t)) for t in input_ids)


def perms_from_ids(input_ids: Sequence[int], K: int) -> List[Tuple[int, ...]]:
    return [token_perm(input_ids[1 + i]) for i in range(K)]


# --------------------------------------------------------------------------
# Samplers
# --------------------------------------------------------------------------
# Above this many distinct sequences, dedup is skipped: the chance that a
# 1e6-example train set collides with a 5e3 test set is ~n_train*n_test/space,
# i.e. < 1e-2 already at 1e9, and utterly negligible beyond.
DEDUP_MAX_SPACE = 10 ** 9


def group_space(task: str, K: int) -> int:
    """Number of DISTINCT length-K sequences that exist for this group."""
    return len(group_elements(task)) ** K


def sample_dataset(task: str, K: int, n_examples: int, seed: int,
                   exclude: Optional[Set[str]] = None):
    """Uniform-over-chain-length sampling, de-duplicated.

    Guard: for small K the sequence space is tiny (e.g. C5 with K=4 has only
    5^4 = 625 distinct sequences). Requesting more than exists would spin
    forever, so the request is capped at 90% of what remains available.
    """
    if task not in TASKS:
        raise ValueError(f"unknown task {task!r}")
    rng = np.random.default_rng(seed)
    space = group_space(task, K)

    # When the sequence space is astronomically larger than the request, a
    # collision is effectively impossible, so the string-key dedup is pure
    # time/memory overhead (it dominates cost at n_train >= 1e6). Skip it.
    dedup = space <= DEDUP_MAX_SPACE
    if not dedup:
        out = []
        for _ in range(n_examples):
            out.append(make_example(task, K, rng))
        return out

    seen: Set[str] = set() if exclude is None else set(exclude)
    available = space - (len(exclude) if exclude else 0)
    target = min(n_examples, max(0, available * 9 // 10))
    if target < n_examples:
        print(f"[data_perm] WARNING: only {space:,} distinct sequences exist "
              f"for {task} K={K}; request {n_examples:,} -> {target:,}. "
              f"Use a larger K.")

    out = []
    attempts, max_attempts = 0, max(target * 20, 2000)
    while len(out) < target and attempts < max_attempts:
        attempts += 1
        inp, tgt = make_example(task, K, rng)
        k = example_key(inp)
        if k in seen:
            continue
        seen.add(k)
        out.append((inp, tgt))
    return out


def make_splits(task: str, K: int, n_train: int = 100_000, n_test: int = 5_000,
                seed: int = 0):
    train = sample_dataset(task, K, n_train, seed=seed)
    train_keys = {example_key(i) for i, _ in train}
    test = sample_dataset(task, K, n_test, seed=seed + 1, exclude=train_keys)
    return train, test


def sample_balanced_by_chain(K: int, per_bin: int, seed: int, task: str = "S5"):
    """Examples with L(x) balanced across {0..K} (constructed directly)."""
    rng = np.random.default_rng(seed)
    out = []
    for L in range(0, K + 1):
        seen: Set[str] = set()
        made, attempts = 0, 0
        max_attempts = per_bin * 200 + 500
        while made < per_bin and attempts < max_attempts:
            attempts += 1
            perms = _make_with_chain(task, K, L, rng)
            if chain_length(perms) != L:
                continue
            inp, tgt = build_example(perms)
            k = example_key(inp)
            if k in seen:
                continue
            seen.add(k)
            out.append((inp, tgt))
            made += 1
    return out


def chain_lengths(examples, K: int) -> List[int]:
    return [chain_length(perms_from_ids(inp, K)) for inp, _ in examples]


# --------------------------------------------------------------------------
# Decoding
# --------------------------------------------------------------------------
def example_to_readable(input_ids: Sequence[int], K: int) -> str:
    perms = perms_from_ids(input_ids, K)
    ans_start = K + 2
    ans = [int(input_ids[ans_start + j]) - DIGIT_OFFSET for j in range(NELEM)]
    body = " * ".join("".join(str(x) for x in p) for p in perms)
    return f"{body}  =  {''.join(str(x) for x in ans)}"


# --------------------------------------------------------------------------
# Acceptance checks
# --------------------------------------------------------------------------
def _acceptance_checks() -> None:
    import os
    print("=" * 70)
    print("data_perm.py ACCEPTANCE CHECKS (permutation composition)")
    print("=" * 70)
    print(f"|S5| = {len(ALL_PERMS)}, |C5| = {len(C5_PERMS)}, vocab = {VOCAB_SIZE}")
    print(f"C5 elements: {C5_PERMS}")

    K = 8
    rng = np.random.default_rng(0)
    for task in TASKS:
        print(f"\n--- 5 examples, task={task}, K={K} (each perm shown as its image) ---")
        for _ in range(5):
            inp, _ = make_example(task, K, rng)
            L = chain_length(perms_from_ids(inp, K))
            print(f"  L(x)={L:>2}  {example_to_readable(inp, K)}")

    print("\n--- manual verification of composition ---")
    c = _CYCLE                       # (0 1 2 3 4): i -> i+1
    cases = [
        ([IDENTITY, IDENTITY], IDENTITY, "id * id = id"),
        ([c, c], _compose(c, c), "c * c = c^2  (i -> i+2)"),
        ([c] * 5, IDENTITY, "c^5 = id (order 5)"),
    ]
    for perms, expected, note in cases:
        got = compose_all(perms)
        ok = "OK" if got == tuple(expected) else "MISMATCH"
        print(f"  {note:<28} -> {got}  [{ok}]")
    # non-commutativity of S5 (the whole point: non-abelian => sequential)
    p, q = (1, 0, 2, 3, 4), (0, 2, 1, 3, 4)
    pq, qp = compose_all([p, q]), compose_all([q, p])
    print(f"  non-commutative S5: p*q={pq} vs q*p={qp}  "
          f"[{'OK (differ)' if pq != qp else 'PROBLEM (equal)'}]")
    # C5 IS commutative (parallelizable control)
    a, b = C5_PERMS[1], C5_PERMS[3]
    print(f"  commutative C5:     a*b={compose_all([a,b])} vs b*a={compose_all([b,a])}  "
          f"[{'OK (equal)' if compose_all([a,b])==compose_all([b,a]) else 'PROBLEM'}]")

    print("\n--- sequence length & loss mask ---")
    inp, tgt = make_example("S5", K, np.random.default_rng(7))
    print(f"  seq_len={len(inp)} == K+8 == {seq_len_for(K)}")
    print(f"  supervised positions (target != -100): {(tgt != IGNORE_INDEX).sum()}"
          f"  (= 5 answer digits + EOS)")

    print("\n--- L(x) histogram: training sampler vs balanced ---")
    Kh, per_bin = 16, 200
    trng = np.random.default_rng(1)          # ONE generator, reused
    tr = [make_example("S5", Kh, trng) for _ in range(4000)]
    trL = chain_lengths(tr, Kh)
    bal = sample_balanced_by_chain(Kh, per_bin=per_bin, seed=1, task="S5")
    balL = chain_lengths(bal, Kh)
    bins = list(range(Kh + 1))
    th = [trL.count(k) for k in bins]
    bh = [balL.count(k) for k in bins]
    print(f"  {'L':>3} | {'train':>6} | {'balanced':>8}")
    for k in bins:
        print(f"  {k:>3} | {th[k]:>6} | {bh[k]:>8}")
    # L=0 has exactly ONE distinct sequence (all identity), so it caps at 1.
    print(f"  balanced flat for L>=1? {min(bh[1:]) == max(bh[1:]) == per_bin}"
          f"   (L=0 capped at {bh[0]} — only one all-identity sequence exists)")

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, axes = plt.subplots(1, 2, figsize=(11, 4), sharex=True)
        axes[0].bar(bins, th, color="#4477aa"); axes[0].set_title("training sampler")
        axes[1].bar(bins, bh, color="#ee6677"); axes[1].set_title(f"balanced (per_bin={per_bin})")
        for ax in axes:
            ax.set_xlabel("chain length L(x) = # non-identity")
        axes[0].set_ylabel("count")
        fig.suptitle(f"L(x) distribution, S5, K={Kh}")
        fig.tight_layout()
        os.makedirs("figures", exist_ok=True)
        p = os.path.join("figures", "perm_chain_length_hist.png")
        fig.savefig(p, dpi=120)
        print(f"\n  histogram saved -> {p}")
    except Exception as e:
        print(f"  (figure not saved: {e})")

    print("\nAll data_perm checks executed.")


if __name__ == "__main__":
    _acceptance_checks()
